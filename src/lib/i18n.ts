/** 需要翻译的全部文本：产品名、元素名、每条结论、通过项 */
export function payload(job: Job, rep: Report, product: string): Translation {
  const findings: Translation['findings'] = {}; const passes: Translation['passes'] = {};
  rep.results.forEach(r => { r.findings.forEach(f => (findings[f.id] = { title: f.title, where: f.where, reason: f.reason, suggestion: f.suggestion })); if (r.passes?.length) passes[r.market] = r.passes; });
  const used = new Set(rep.results.flatMap(r => r.findings.map(f => f.elementId)));
  const elements = Object.fromEntries(rep.elements.filter(e => used.has(e.id)).map(e => [e.id, e.label]));
  void job; return { product, elements, findings, passes };
}

const SYS = (lang: 'en' | 'ja') => `You are a senior localization specialist for cross-border e-commerce compliance reports.
Translate every string VALUE of the given JSON from Chinese into ${lang === 'en' ? 'natural, professional English' : '自然で丁寧なビジネス日本語'}.
Rules: keep all keys and the structure exactly the same; keep quoted product copy, brand names, model names and codes (e.g. "LUCKY 4 SET", MRP, SKU) unchanged; keep it concise; do not add notes. Output the JSON only.`;

/** 取翻译：演示数据读预生成文件；真实结果调用复核模型并缓存到报告里 */
export async function getTranslation(job: Job, rep: Report, lang: 'en' | 'ja', demo: boolean, product: string): Promise<Translation> {
  if (rep.i18n?.[lang]) return rep.i18n[lang]!;
  if (demo) {
    const r = await fetch(`i18n/demo-${job.demoId || 'tea'}.json`); if (!r.ok) throw new Error('示例翻译加载失败');
    const all = await r.json(); return all[lang];
  }
  if (!hasLive()) throw new Error('翻译真实报告需要配置 Key');
  const src = payload(job, rep, product);
  const { json } = await chatJSON(loadSettings(), { role: 'review', system: SYS(lang), user: JSON.stringify(src), temperature: 0.2 });
  const out: Translation = { product: json.product || product, elements: { ...src.elements, ...(json.elements || {}) }, findings: { ...src.findings }, passes: { ...src.passes, ...(json.passes || {}) } };
  for (const k of Object.keys(src.findings)) out.findings[k] = { ...src.findings[k], ...(json.findings?.[k] || {}) };
  rep.i18n = { ...(rep.i18n || {}), [lang]: out };
  return out;
}
